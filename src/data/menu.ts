export function formatAOA(amount: number): string {
  // Format as Angolan Kwanza e.g. "8.500 Kz"
  const formatted = new Intl.NumberFormat('pt-AO', {
    maximumFractionDigits: 0,
  }).format(amount).replace(/,/g, '.');
  return `${formatted} Kz`;
}
